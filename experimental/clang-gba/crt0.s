.align 2
_gba_start:
    ldr sp, =0x03007F00
    ldr r0, =__data_load_start
    ldr r1, =__data_start
    ldr r2, =__data_end
1:
    cmp r1, r2
    ldrlo r3, [r0], #4
    strlo r3, [r1], #4
    blo 1b
    ldr r1, =__bss_start
    ldr r2, =__bss_end
    mov r3, #0
2:
    cmp r1, r2
    strlo r3, [r1], #4
    blo 2b
    adr r0, _thumb_start+1
    bx r0
.thumb
.thumb_func
_thumb_start:
    bl main
3:
    b 3b
